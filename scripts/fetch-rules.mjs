#!/usr/bin/env node
// Download the Magic Comprehensive Rules and split them into small,
// searchable Markdown files under rules/.
//
// Usage:
//   node scripts/fetch-rules.mjs                 # find the latest TXT on magic.wizards.com
//   node scripts/fetch-rules.mjs <url>           # a specific TXT url
//   node scripts/fetch-rules.mjs <path/to/file>  # a TXT file you downloaded yourself
//
// Output (all generated; do not hand-edit):
//   rules/VERSION.json        effective date and source
//   rules/raw/MagicCompRules.txt
//   rules/cr/INDEX.md         every chapter and section with its file
//   rules/cr/<num>-<slug>.md  one file per section (e.g. 601-casting-spells.md)
//   rules/cr/<num>-<slug>/    big sections (701, 702, ...) split per top-level rule
//   rules/glossary/<letter>.md
//
// Every rule stays on its own line starting with its number, so
//   grep -rn "^601.2c" rules/cr
// finds it. See rules/README.md.

import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { decodeRulesText, parseRules, slugify } from "./lib/cr-parse.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(ROOT, "rules");
const RULES_PAGE = "https://magic.wizards.com/en/rules";
const USER_AGENT = "mtg-engine-rules-fetcher/1.0 (personal fan project)";

// Sections larger than this are split into one file per top-level rule,
// so a single file stays small enough to read in one go.
const SPLIT_THRESHOLD_BYTES = 40_000;

async function fetchBytes(url) {
  const res = await fetch(url, { headers: { "User-Agent": USER_AGENT } });
  if (!res.ok) throw new Error(`GET ${url} failed: HTTP ${res.status}`);
  return new Uint8Array(await res.arrayBuffer());
}

async function findLatestTxtUrl() {
  const html = new TextDecoder().decode(await fetchBytes(RULES_PAGE));
  const hrefs = [...html.matchAll(/href\s*=\s*["']([^"']+\.txt)["']/gi)].map((m) => m[1]);
  const txt = hrefs.find((h) => /MagicCompRules/i.test(h)) ?? hrefs[0];
  if (!txt) {
    throw new Error(
      `No .txt link found on ${RULES_PAGE}. Download the TXT by hand and run:\n` +
        "  node scripts/fetch-rules.mjs path/to/MagicCompRules.txt",
    );
  }
  return new URL(txt, RULES_PAGE).href; // also encodes spaces in the file name
}

async function loadSource(arg) {
  if (arg && !/^https?:\/\//i.test(arg)) {
    return { bytes: new Uint8Array(await readFile(arg)), source: `local file ${path.basename(arg)}` };
  }
  const url = arg ? new URL(arg).href : await findLatestTxtUrl();
  console.log(`Downloading ${url}`);
  return { bytes: await fetchBytes(url), source: url };
}

function header(title, effective) {
  return (
    `# ${title}\n\n` +
    `<!-- Generated by scripts/fetch-rules.mjs from the Comprehensive Rules ` +
    `effective ${effective ?? "(unknown date)"}. Do not edit. -->\n\n`
  );
}

function entriesText(entries) {
  return entries.map((e) => e.text).join("\n\n") + "\n";
}

/** A top-level rule like "702.9. Flying" is a title; long rule text is not. */
function topRuleTitle(entry) {
  const body = entry.text.split("\n")[0].replace(/^\d{3}\.\d+\.\s*/, "");
  if (body.length <= 60 && !/[.:]$/.test(body)) return body;
  return body.split(/\s+/).slice(0, 6).join(" ");
}

async function main() {
  const { bytes, source } = await loadSource(process.argv[2]);
  const text = decodeRulesText(bytes);
  const rules = parseRules(text);

  for (const dir of ["cr", "glossary", "raw"]) await rm(path.join(OUT, dir), { recursive: true, force: true });
  await mkdir(path.join(OUT, "cr"), { recursive: true });
  await mkdir(path.join(OUT, "glossary"), { recursive: true });
  await mkdir(path.join(OUT, "raw"), { recursive: true });

  await writeFile(path.join(OUT, "raw", "MagicCompRules.txt"), text);
  await writeFile(
    path.join(OUT, "VERSION.json"),
    JSON.stringify({ effective: rules.effective, source, sections: rules.sections.length, glossaryTerms: rules.glossary.length }, null, 2) + "\n",
  );

  const index = [header("Comprehensive Rules index", rules.effective)];
  index.push(
    "Each section is one file. Large sections are folders with one file per top-level rule.\n" +
      "Find a rule by number: `grep -rn \"^702.19b\" rules/cr` or `node scripts/rule.mjs 702.19b`.\n",
  );

  for (const chapter of rules.chapters) {
    index.push(`\n## ${chapter.num}. ${chapter.title}\n`);
    for (const section of rules.sections.filter((s) => s.chapter === chapter.num)) {
      const name = `${section.num}-${slugify(section.title)}`;
      const body = entriesText(section.entries);
      const title = `${section.num}. ${section.title}`;

      if (Buffer.byteLength(body) <= SPLIT_THRESHOLD_BYTES) {
        await writeFile(path.join(OUT, "cr", `${name}.md`), header(title, rules.effective) + body);
        index.push(`- ${title} — \`cr/${name}.md\``);
        continue;
      }

      // Split a big section into one file per top-level rule.
      const dir = path.join(OUT, "cr", name);
      await mkdir(dir, { recursive: true });
      index.push(`- ${title} — \`cr/${name}/\``);
      const tops = [...new Set(section.entries.map((e) => e.top))];
      for (const top of tops) {
        const group = section.entries.filter((e) => e.top === top);
        const first = group[0];
        const subTitle = topRuleTitle(first);
        const file = `${top}-${slugify(subTitle) || "rule"}.md`;
        await writeFile(path.join(dir, file), header(`${top}. ${subTitle} (in ${title})`, rules.effective) + entriesText(group));
        index.push(`  - ${top} ${subTitle} — \`cr/${name}/${file}\``);
      }
    }
  }

  index.push("\n## Glossary\n");
  const byLetter = new Map();
  for (const g of rules.glossary) {
    const first = g.term[0]?.toLowerCase() ?? "_";
    const key = /[a-z]/.test(first) ? first : "0-9";
    if (!byLetter.has(key)) byLetter.set(key, []);
    byLetter.get(key).push(g);
  }
  for (const [key, entries] of [...byLetter].sort(([a], [b]) => a.localeCompare(b))) {
    const body = entries.map((g) => `## ${g.term}\n${g.text}`).join("\n\n") + "\n";
    await writeFile(path.join(OUT, "glossary", `${key}.md`), header(`Glossary: ${key.toUpperCase()}`, rules.effective) + body);
    index.push(`- ${key.toUpperCase()} (${entries.length} terms) — \`glossary/${key}.md\``);
  }

  await writeFile(path.join(OUT, "cr", "INDEX.md"), index.join("\n") + "\n");

  const ruleCount = rules.sections.reduce((n, s) => n + s.entries.length, 0);
  console.log(
    `Rules effective ${rules.effective}: ${rules.sections.length} sections, ${ruleCount} rules, ` +
      `${rules.glossary.length} glossary terms written to rules/.`,
  );
}

main().catch((err) => {
  console.error(err.message);
  process.exit(1);
});
