//! The vector check's Rust half (docs/odin-port.md, "Verifying translated code"): `odingen vector-patch <crates-dir>`
//! rewrites a scratch COPY of the engine's sources so that every plain function logs its first calls: the arguments,
//! the result and the `&mut` arguments after the call, as serde JSON. The Odin harness replays those calls against
//! the translated procedures and compares. Never run on the real tree.
//!
//! Each candidate `fn name` (a free function or an inherent method, not generic, with plain parameters and no
//! reference in its result) is renamed `__orig_name` in place, and a wrapper with the original signature is inserted
//! before it. Edits are byte splices at syn's spans, so the rest of each file is untouched.

use std::path::{Path, PathBuf};

use quote::ToTokens;
use syn::spanned::Spanned;
use syn::{FnArg, ImplItem, Item, Pat, ReturnType, Signature};

use crate::translate::proc_name_for;

/// The logging runtime added to the patched crate as `crate::vector_log`.
const RUNTIME: &str = r#"//! GENERATED by odingen vector-patch, in a scratch copy only: logs the first calls of each wrapped function.
use std::cell::Cell;
use std::collections::HashSet;
use std::hash::{Hash, Hasher};
use std::io::Write;
use std::sync::atomic::{AtomicU32, Ordering};
use std::sync::{Mutex, OnceLock};

/// Autoref specialization: serde JSON for types that implement Serialize, nothing for the rest.
pub struct W<'a, T: ?Sized>(pub &'a T);
pub trait ViaSerde {
    fn vector_json(&self) -> Option<String>;
}
impl<T: serde::Serialize + ?Sized> ViaSerde for W<'_, T> {
    fn vector_json(&self) -> Option<String> {
        serde_json::to_string(self.0).ok()
    }
}
pub trait ViaNothing {
    fn vector_json(&self) -> Option<String>;
}
impl<T: ?Sized> ViaNothing for &W<'_, T> {
    fn vector_json(&self) -> Option<String> {
        None
    }
}

struct Log {
    out: std::io::BufWriter<std::fs::File>,
    states: std::io::BufWriter<std::fs::File>,
    seen: HashSet<u64>,
}

static LOG: OnceLock<Option<Mutex<Log>>> = OnceLock::new();

fn log() -> Option<&'static Mutex<Log>> {
    LOG.get_or_init(|| {
        let p = std::env::var("VECTOR_LOG").ok()?;
        let out = std::fs::File::create(&p).ok()?;
        let states = std::fs::File::create(format!("{p}.values")).ok()?;
        Some(Mutex::new(Log { out: std::io::BufWriter::new(out), states: std::io::BufWriter::new(states), seen: HashSet::new() }))
    })
    .as_ref()
}

thread_local! {
    /// Set while serializing: calls made by Serialize impls aren't logged.
    static BUSY: Cell<bool> = const { Cell::new(false) };
}

/// Whether to log this call: the first three of each function, then the 10th, 100th, 1000th, ...
pub fn begin(c: &AtomicU32) -> bool {
    if log().is_none() || BUSY.with(|b| b.get()) {
        return false;
    }
    let n = c.fetch_add(1, Ordering::Relaxed) + 1;
    n <= 3 || {
        let mut k = n;
        while k % 10 == 0 {
            k /= 10;
        }
        k == 1
    }
}

pub fn capture(on: bool, f: impl FnOnce() -> Vec<Option<String>>) -> Option<Vec<Option<String>>> {
    if !on {
        return None;
    }
    BUSY.with(|b| b.set(true));
    let v = f();
    BUSY.with(|b| b.set(false));
    Some(v)
}

/// Large values (game states) go once to `<log>.values`, referenced by hash.
fn value(l: &mut Log, v: &Option<String>) -> String {
    match v {
        // Not Serialize: distinct from a serialized `None` (null).
        None => "{\"$unlogged\":true}".into(),
        Some(s) if s.len() < 4096 => s.clone(),
        Some(s) => {
            let mut h = std::collections::hash_map::DefaultHasher::new();
            s.hash(&mut h);
            let k = h.finish();
            if l.seen.insert(k) {
                let _ = writeln!(l.states, "{{\"h\":\"{k:016x}\",\"v\":{s}}}");
                let _ = l.states.flush();
            }
            format!("{{\"$ref\":\"{k:016x}\"}}")
        }
    }
}

pub fn end(name: &str, file: &str, args: Option<Vec<Option<String>>>, f: impl FnOnce() -> (Option<String>, Vec<Option<String>>)) {
    let Some(args) = args else { return };
    BUSY.with(|b| b.set(true));
    let (ret, after) = f();
    BUSY.with(|b| b.set(false));
    let Some(m) = log() else { return };
    let mut l = m.lock().unwrap();
    let args: Vec<String> = args.iter().map(|a| value(&mut l, a)).collect();
    let ret = value(&mut l, &ret);
    let after: Vec<String> = after.iter().map(|a| value(&mut l, a)).collect();
    let line = format!(
        "{{\"f\":{},\"file\":{},\"args\":[{}],\"ret\":{},\"after\":[{}]}}",
        serde_json::to_string(name).unwrap(),
        serde_json::to_string(file).unwrap(),
        args.join(","),
        ret,
        after.join(",")
    );
    let _ = writeln!(l.out, "{line}");
    let _ = l.out.flush();
}
"#;

/// `only`: the procedure names to wrap (the harness's cases); every candidate when None. Wrapping all ~14k
/// functions makes the engine crate too big to compile in 16 GB.
pub fn patch(crates: &Path, only: Option<&std::collections::BTreeSet<String>>) {
    let src = crates.join("engine/src");
    let mut wrapped = 0;
    let mut files = 0;
    for entry in walkdir::WalkDir::new(&src).into_iter().filter_map(Result::ok) {
        let p = entry.path();
        if p.extension().is_none_or(|e| e != "rs") || p.components().any(|c| c.as_os_str() == "tests") {
            continue;
        }
        let text = std::fs::read_to_string(p).expect("read");
        let Ok(file) = syn::parse_file(&text) else { continue };
        let rel = p.strip_prefix(crates).unwrap_or(p).to_path_buf();
        let mut edits: Vec<(usize, usize, String)> = Vec::new();
        collect(&file.items, &text, &rel, &mut edits, only);
        if edits.is_empty() {
            continue;
        }
        wrapped += edits.len() / 2;
        files += 1;
        // Apply from the end so earlier offsets stay valid.
        edits.sort_by(|a, b| b.0.cmp(&a.0).then(b.1.cmp(&a.1)));
        let mut out = text.clone();
        for (start, end, s) in edits {
            out.replace_range(start..end, &s);
        }
        std::fs::write(p, out).expect("write");
    }
    std::fs::write(src.join("vector_log.rs"), RUNTIME).expect("runtime");
    let lib = src.join("lib.rs");
    let mut l = std::fs::read_to_string(&lib).expect("lib.rs");
    l.push_str("\n#[doc(hidden)]\npub mod vector_log;\n");
    std::fs::write(&lib, l).expect("lib.rs");
    eprintln!("vector-patch: {wrapped} functions wrapped in {files} files");
}

fn collect(items: &[Item], text: &str, rel: &Path, edits: &mut Vec<(usize, usize, String)>, only: Option<&std::collections::BTreeSet<String>>) {
    for item in items {
        match item {
            Item::Fn(f) if !is_test(&f.attrs) => {
                wrap(None, &f.attrs, &f.vis.to_token_stream().to_string(), &f.sig, item.span(), text, rel, edits, only);
            }
            Item::Impl(im) if im.trait_.is_none() && im.generics.params.is_empty() && !is_test(&im.attrs) => {
                let syn::Type::Path(tp) = &*im.self_ty else { continue };
                let Some(owner) = tp.path.segments.last().map(|s| s.ident.to_string()) else { continue };
                if tp.path.segments.last().is_some_and(|s| !s.arguments.is_empty()) {
                    continue;
                }
                for ii in &im.items {
                    if let ImplItem::Fn(f) = ii {
                        if !is_test(&f.attrs) {
                            wrap(Some(&owner), &f.attrs, &f.vis.to_token_stream().to_string(), &f.sig, ii.span(), text, rel, edits, only);
                        }
                    }
                }
            }
            Item::Mod(m) if !is_test(&m.attrs) => {
                if let Some((_, items)) = &m.content {
                    collect(items, text, rel, edits, only);
                }
            }
            _ => {}
        }
    }
}

fn is_test(attrs: &[syn::Attribute]) -> bool {
    attrs.iter().any(|a| {
        let s = a.to_token_stream().to_string();
        s.contains("cfg (test)") || s.contains("cfg(test)") || s.starts_with("# [test]")
    })
}

/// Splices for one function: the wrapper before the item, and `__orig_` on its name.
#[allow(clippy::too_many_arguments)]
fn wrap(owner: Option<&str>, attrs: &[syn::Attribute], vis: &str, sig: &Signature, span: proc_macro2::Span, text: &str, rel: &Path, edits: &mut Vec<(usize, usize, String)>, only: Option<&std::collections::BTreeSet<String>>) {
    if crate::body::generic_kind(sig).is_some()
        || sig.constness.is_some()
        || sig.asyncness.is_some()
        || sig.unsafety.is_some()
        || sig.abi.is_some()
        || sig.variadic.is_some()
    {
        return;
    }
    let ret_tokens = match &sig.output {
        ReturnType::Default => String::new(),
        ReturnType::Type(_, t) => t.to_token_stream().to_string(),
    };
    // A result that borrows (`&T`, `Iter<'_, T>`) keeps an argument borrowed past the call.
    if ret_tokens.contains('&') || ret_tokens.contains('\'') || ret_tokens.contains("impl") || ret_tokens == "!" {
        return;
    }
    let name = sig.ident.to_string();
    let mut params = Vec::new();
    let mut pass = Vec::new();
    let mut before = Vec::new();
    let mut after = Vec::new();
    let mut has_self = false;
    // A parameter under its own `#[cfg]` may not exist in this build.
    if sig.inputs.iter().any(|i| match i {
        FnArg::Receiver(r) => !r.attrs.is_empty(),
        FnArg::Typed(t) => !t.attrs.is_empty(),
    }) {
        return;
    }
    for input in &sig.inputs {
        match input {
            FnArg::Receiver(r) => {
                if r.colon_token.is_some() {
                    return; // `self: Box<Self>` and the like
                }
                has_self = true;
                let s = match (&r.reference, r.mutability.is_some()) {
                    (Some(_), true) => "&mut self",
                    (Some(_), false) => "&self",
                    (None, _) => "self",
                };
                params.push(s.to_string());
                pass.push("self".to_string());
                before.push("vj!(self)".to_string());
                if s == "&mut self" {
                    after.push("vj!(self)".to_string());
                }
            }
            FnArg::Typed(pt) => {
                let Pat::Ident(pi) = &*pt.pat else { return };
                if pi.by_ref.is_some() || pi.subpat.is_some() {
                    return;
                }
                let ty = pt.ty.to_token_stream().to_string();
                if ty.contains("impl ") || ty.contains("dyn ") && ty.contains("FnMut") {
                    return;
                }
                let n = pi.ident.to_string();
                params.push(format!("{n}: {ty}"));
                pass.push(n.clone());
                before.push(format!("vj!({n})"));
                if matches!(&*pt.ty, syn::Type::Reference(r) if r.mutability.is_some()) {
                    after.push(format!("vj!({n})"));
                }
            }
        }
    }
    // The Odin procedure's name (the harness dispatches on it) and the file, which disambiguates clashes.
    let fake = crate::model::FnDef { sig: sig.clone(), block: syn::parse_quote!({}), file: PathBuf::from(rel), self_ty: owner.map(str::to_string) };
    let proc = proc_name_for(owner, &name, &fake);
    if only.is_some_and(|o| !o.contains(&proc)) {
        return;
    }
    let file = rel.to_string_lossy().to_string();
    let cfgs: String = attrs.iter().filter(|a| a.path().is_ident("cfg")).map(|a| a.to_token_stream().to_string() + "\n").collect();
    let ret = match &sig.output {
        ReturnType::Default => String::new(),
        ReturnType::Type(_, t) => format!(" -> {}", t.to_token_stream()),
    };
    let call = if has_self || owner.is_some() {
        format!("Self::__orig_{name}({})", pass.join(", "))
    } else {
        format!("__orig_{name}({})", pass.join(", "))
    };
    let wrapper = format!(
        "{cfgs}#[allow(unused_mut, clippy::all)]\n{vis} fn {name}{lifetimes}({params}){ret} {where_}{{\n\
         \x20   #[allow(unused_imports)] use crate::vector_log::{{ViaNothing as _, ViaSerde as _}};\n\
         \x20   macro_rules! vj {{ ($e:expr) => {{ (&crate::vector_log::W(&$e)).vector_json() }}; }}\n\
         \x20   static __VC: ::std::sync::atomic::AtomicU32 = ::std::sync::atomic::AtomicU32::new(0);\n\
         \x20   let __vk = crate::vector_log::begin(&__VC);\n\
         \x20   let __va = crate::vector_log::capture(__vk, || vec![{before}]);\n\
         \x20   let __vr = {call};\n\
         \x20   crate::vector_log::end({proc:?}, {file:?}, __va, || (vj!(__vr), vec![{after}]));\n\
         \x20   __vr\n}}\n",
        params = params.join(", "),
        lifetimes = if sig.generics.params.is_empty() { String::new() } else { sig.generics.to_token_stream().to_string() },
        where_ = sig.generics.where_clause.as_ref().map(|w| w.to_token_stream().to_string() + " ").unwrap_or_default(),
        before = before.join(", "),
        after = after.join(", "),
    );
    let item_start = span.byte_range().start;
    let id = sig.ident.span().byte_range();
    if text.get(id.clone()) != Some(name.as_str()) {
        return; // spans unavailable or off: leave the function alone
    }
    edits.push((item_start, item_start, wrapper));
    edits.push((id.start, id.end, format!("__orig_{name}")));
}
