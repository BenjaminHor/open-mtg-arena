//! The replay harness's Rust half (docs/odin-port.md, "Replaying recorded games"): `odingen trace-patch <crates-dir>`
//! rewrites a scratch COPY of the crates so that a recorded game logs, for every engine and phase-ast function, the
//! first step whose reducer call reaches it. The Odin replay joins that with the translation's stubs: the
//! untranslated functions a whole game needs, ordered by first use, beyond the first stub each step stops at.
//! Never run on the real tree.
//!
//! Each function body (free functions, inherent and trait-impl methods, trait methods' default bodies; not `const fn`,
//! not functions nested in other functions or in macros, not impls for non-path types such as `&T` or `[T]`) gets
//! one statement first:
//! a per-function static flag and a call to `phase_ast::__first_use::hit`, which logs only inside the reducer call
//! that phase_ai's `run_ai_action` makes (the AI's own search and simulations call the same functions, but they
//! aren't what the Odin engine must run to replay a game). `record-games` tells it the step. Edits are byte splices
//! at syn's spans, so the rest of each file is untouched.

use std::path::Path;

use syn::spanned::Spanned;
use syn::{ImplItem, Item, TraitItem};

use crate::translate::proc_name_for;

/// The runtime, added to phase-ast (the lowest crate) as `phase_ast::__first_use` and re-exported by the engine.
const RUNTIME: &str = r#"//! GENERATED by odingen trace-patch, in a scratch copy only: logs each function's first use inside the reducer.
use std::cell::Cell;
use std::io::Write;
use std::sync::atomic::{AtomicBool, AtomicUsize, Ordering};
use std::sync::{Mutex, OnceLock};

static STEP: AtomicUsize = AtomicUsize::new(0);
static LOG: OnceLock<Option<Mutex<std::io::BufWriter<std::fs::File>>>> = OnceLock::new();

thread_local! {
    /// Depth of reducer calls on this thread (the AI's search runs elsewhere or outside them).
    static IN: Cell<u32> = const { Cell::new(0) };
}

pub fn set_step(step: usize) {
    STEP.store(step, Ordering::Relaxed);
}
pub fn enter() {
    IN.with(|c| c.set(c.get() + 1));
}
pub fn leave() {
    IN.with(|c| c.set(c.get() - 1));
    if let Some(Some(l)) = LOG.get() {
        let _ = l.lock().unwrap().flush();
    }
}

#[inline]
pub fn hit(first: &AtomicBool, name: &str, file: &str) {
    if first.load(Ordering::Relaxed) || IN.with(|c| c.get()) == 0 {
        return;
    }
    first.store(true, Ordering::Relaxed);
    let log = LOG.get_or_init(|| {
        let p = std::env::var("FIRST_USE_LOG").ok()?;
        Some(Mutex::new(std::io::BufWriter::new(std::fs::File::create(p).ok()?)))
    });
    if let Some(l) = log {
        let _ = writeln!(l.lock().unwrap(), "{}\t{}\t{}", STEP.load(Ordering::Relaxed), name, file);
    }
}
"#;

pub fn patch(crates: &Path) {
    let mut total = 0;
    for (krate, rt) in [("phase-ast", "crate::__first_use"), ("engine", "::phase_ast::__first_use")] {
        let src = crates.join(krate).join("src");
        for entry in walkdir::WalkDir::new(&src).into_iter().filter_map(Result::ok) {
            let p = entry.path();
            if p.extension().is_none_or(|e| e != "rs") || p.components().any(|c| c.as_os_str() == "tests") {
                continue;
            }
            let text = std::fs::read_to_string(p).expect("read");
            let Ok(file) = syn::parse_file(&text) else { continue };
            let rel = p.strip_prefix(crates).unwrap_or(p).to_path_buf();
            let mut edits: Vec<(usize, String)> = Vec::new();
            collect(&file.items, &text, &rel, rt, &mut edits);
            if edits.is_empty() {
                continue;
            }
            total += edits.len();
            edits.sort_by(|a, b| b.0.cmp(&a.0));
            let mut out = text.clone();
            for (at, s) in edits {
                out.insert_str(at, &s);
            }
            std::fs::write(p, out).expect("write");
        }
    }
    std::fs::write(crates.join("phase-ast/src/__first_use.rs"), RUNTIME).expect("runtime");
    append(&crates.join("phase-ast/src/lib.rs"), "\n#[doc(hidden)]\npub mod __first_use;\n");
    append(&crates.join("engine/src/lib.rs"), "\n#[doc(hidden)]\npub use phase_ast::__first_use;\n");

    // The reducer boundary of run_ai_action, and the step record-games is on.
    replace_once(
        &crates.join("phase-ai/src/auto_play.rs"),
        "apply_verified_ai_priority_pass(state, actor, &contract, action.clone())",
        "{ engine::__first_use::enter(); let r = apply_verified_ai_priority_pass(state, actor, &contract, action.clone()); engine::__first_use::leave(); r }",
    );
    replace_once(
        &crates.join("phase-ai/src/auto_play.rs"),
        "apply_interaction(state, actor, semantic_owner, action.clone())",
        "{ engine::__first_use::enter(); let r = apply_interaction(state, actor, semantic_owner, action.clone()); engine::__first_use::leave(); r }",
    );
    replace_once(
        &crates.join("phase-ai/src/bin/record_games.rs"),
        "let decision = eligible_ai_decision(&state, &ai_players);",
        "let decision = eligible_ai_decision(&state, &ai_players);\n            engine::__first_use::set_step(step);",
    );
    eprintln!("trace-patch: {total} functions traced");
}

fn append(p: &Path, s: &str) {
    let mut t = std::fs::read_to_string(p).expect("read");
    t.push_str(s);
    std::fs::write(p, t).expect("write");
}

/// The patch must land exactly once: a change upstream should stop the trace, not silently break it.
fn replace_once(p: &Path, from: &str, to: &str) {
    let t = std::fs::read_to_string(p).expect("read");
    let n = t.matches(from).count();
    assert!(n == 1, "trace-patch: expected `{from}` once in {}, found {n}", p.display());
    std::fs::write(p, t.replacen(from, to, 1)).expect("write");
}

fn collect(items: &[Item], text: &str, rel: &Path, rt: &str, edits: &mut Vec<(usize, String)>) {
    for item in items {
        match item {
            Item::Fn(f) if !is_test(&f.attrs) => trace(None, &f.sig, &f.block, text, rel, rt, edits),
            Item::Impl(im) if !is_test(&im.attrs) => {
                let syn::Type::Path(tp) = &*im.self_ty else { continue };
                let Some(owner) = tp.path.segments.last().map(|s| s.ident.to_string()) else { continue };
                for ii in &im.items {
                    if let ImplItem::Fn(f) = ii {
                        if !is_test(&f.attrs) {
                            trace(Some(&owner), &f.sig, &f.block, text, rel, rt, edits);
                        }
                    }
                }
            }
            Item::Trait(t) if !is_test(&t.attrs) => {
                let owner = t.ident.to_string();
                for ti in &t.items {
                    if let TraitItem::Fn(f) = ti {
                        if let (Some(block), false) = (&f.default, is_test(&f.attrs)) {
                            trace(Some(&owner), &f.sig, block, text, rel, rt, edits);
                        }
                    }
                }
            }
            Item::Mod(m) if !is_test(&m.attrs) => {
                if let Some((_, items)) = &m.content {
                    collect(items, text, rel, rt, edits);
                }
            }
            _ => {}
        }
    }
}

fn is_test(attrs: &[syn::Attribute]) -> bool {
    use quote::ToTokens;
    attrs.iter().any(|a| {
        let s = a.to_token_stream().to_string();
        let s: String = s.chars().filter(|c| !c.is_whitespace()).collect();
        // `cfg(test)`, `cfg(any(test, ..))`; not `cfg(not(test))`, which is production code.
        let names_test = ["(test)", "(test,", ",test)", ",test,"].iter().any(|t| s.contains(t));
        (s.starts_with("#[cfg(") && names_test && !s.contains("not(test")) || s.starts_with("#[test]")
    })
}

fn trace(owner: Option<&str>, sig: &syn::Signature, block: &syn::Block, text: &str, rel: &Path, rt: &str, edits: &mut Vec<(usize, String)>) {
    if sig.constness.is_some() {
        return;
    }
    // A body starting with inner attributes (`#![allow(..)]`) must keep them first.
    let open = block.brace_token.span.open().byte_range();
    if text.get(open.end..).is_some_and(|t| t.trim_start().starts_with("#!")) {
        return;
    }
    if text.get(open.clone()) != Some("{") || block.span().byte_range().is_empty() {
        return; // spans unavailable or off: leave the function alone
    }
    let fake = crate::model::FnDef { sig: sig.clone(), block: syn::parse_quote!({}), file: rel.to_path_buf(), self_ty: owner.map(str::to_string) };
    let proc = proc_name_for(owner, &sig.ident.to_string(), &fake);
    let file = rel.to_string_lossy().to_string();
    edits.push((
        open.end,
        format!(" {{ static __FU: ::std::sync::atomic::AtomicBool = ::std::sync::atomic::AtomicBool::new(false); {rt}::hit(&__FU, {proc:?}, {file:?}); }}"),
    ));
}
