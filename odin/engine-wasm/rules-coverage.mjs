// Which Comprehensive Rules the Odin engine implements, as a checklist (owner, 2026-11-25): every rule and subrule in
// rules/cr, marked by whether the engine's code cites it (odin/engine/game, "CR 601.2a") and whether a test cites it
// (odin/tests). A citation is the engine's own claim that the code carries the rule out, checked by review and by
// the tests that cite it; a rule nobody cites isn't implemented yet (or is implemented without saying so, which the
// code's rule "cite the CR" doesn't allow).
// Usage: node odin/engine-wasm/rules-coverage.mjs [--out docs/odin-rules-coverage.md]
import { readFileSync, readdirSync, writeFileSync } from "node:fs";

const root = new URL("../../", import.meta.url).pathname;

// Every rule: "601.2a Text" or "601.2. Text" at the start of a line.
const rules = [];
const sections = new Map(); // "601" -> title
// A section is a file (601-casting-spells.md) or, for the long ones (701, 702), a folder of one file per rule.
for (const entry of readdirSync(`${root}rules/cr`, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
  const m = entry.name.match(/^(\d{3})-(.*?)(\.md)?$/);
  if (!m) continue;
  sections.set(m[1], m[2].replace(/-/g, " "));
  const files = entry.isDirectory()
    ? readdirSync(`${root}rules/cr/${entry.name}`).filter((f) => f.endsWith(".md")).sort((a, b) => a.localeCompare(b, undefined, { numeric: true })).map((f) => `${entry.name}/${f}`)
    : [entry.name];
  for (const file of files) {
    for (const line of readFileSync(`${root}rules/cr/${file}`, "utf8").split("\n")) {
      const r = line.match(/^(\d{3}\.\d+[a-z]*)\.? (.*)$/);
      if (r) rules.push({ id: r[1], section: m[1], text: r[2] });
    }
  }
}

// Citations: in a line that says "CR", every rule number on it ("CR 119.2-119.4", "CR 603.4, 603.6a"). A range of
// subrules ("601.2a-h", "117.3c-5") cites each rule in it.
function citations(dir) {
  const found = new Map(); // id -> [file:line]
  const walk = (d) => {
    for (const e of readdirSync(d, { withFileTypes: true })) {
      const p = `${d}/${e.name}`;
      if (e.isDirectory()) walk(p);
      else if (e.name.endsWith(".odin")) {
        readFileSync(p, "utf8").split("\n").forEach((line, i) => {
          if (!/\bCR\b/.test(line)) return;
          const where = `${p.slice(root.length)}:${i + 1}`;
          const add = (id) => {
            if (!found.has(id)) found.set(id, []);
            found.get(id).push(where);
          };
          for (const m of line.matchAll(/\b(\d{3})\.(\d+)([a-z]?)(?:-(\d{3}\.)?(\d+)?([a-z])?)?/g)) {
            const [, sec, num, letter, toSec, toNum, toLetter] = m;
            add(`${sec}.${num}${letter}`);
            if (letter && toLetter && !toSec && !toNum) {
              // "601.2a-h": each subrule in the range.
              for (let c = letter.charCodeAt(0) + 1; c <= toLetter.charCodeAt(0); c++) add(`${sec}.${num}${String.fromCharCode(c)}`);
            } else if (toNum && (!toSec || toSec === `${sec}.`)) {
              // "119.2-119.4", "117.3-5": each numbered rule in the range.
              for (let n = Number(num) + 1; n <= Number(toNum); n++) add(`${sec}.${n}`);
            }
          }
        });
      }
    }
  };
  walk(`${root}${dir}`);
  return found;
}
const engine = citations("odin/engine/game");
const tests = citations("odin/tests");

// The ranges the game the app plays doesn't reach: multiplayer (800-811) and casual variants (900s).
const inScope = (section) => Number(section) < 800;

const status = (id) => (engine.has(id) ? (tests.has(id) ? "tested" : "cited") : tests.has(id) ? "test only" : "not yet");
const bySection = new Map();
for (const r of rules) {
  if (!bySection.has(r.section)) bySection.set(r.section, []);
  bySection.get(r.section).push(r);
}
const count = (list, s) => list.filter((r) => status(r.id) === s).length;
const inScopeRules = rules.filter((r) => inScope(r.section));
const pct = (a, b) => (b ? `${Math.round((100 * a) / b)}%` : "-");
const implemented = (list) => count(list, "tested") + count(list, "cited");

const lines = [];
lines.push("# Odin engine: Comprehensive Rules coverage");
lines.push("");
lines.push("Generated by `node odin/engine-wasm/rules-coverage.mjs --out docs/odin-rules-coverage.md`; don't edit by hand.");
lines.push("A rule counts as implemented when the engine's code cites it (`CR 601.2a` in odin/engine/game), and as tested when");
lines.push("a test cites it too (odin/tests). A citation is the code's claim, checked by rules reviews and the tests; it doesn't");
lines.push("say every case of the rule is handled. Multiplayer (800-811) and casual variants (900s) are out of scope for the");
lines.push("two-player game the app plays.");
lines.push("");
lines.push(`**In scope (100-799): ${implemented(inScopeRules)} of ${inScopeRules.length} rules implemented (${pct(implemented(inScopeRules), inScopeRules.length)}), ${count(inScopeRules, "tested")} of them tested.**`);
lines.push("");
lines.push("Legend: ✅ implemented and tested · 🟡 implemented, no test cites it · 🧪 a test cites it, the code doesn't · ⬜ not yet");
lines.push("");
lines.push("| Section | Rules | Implemented | Tested |");
lines.push("| --- | ---: | ---: | ---: |");
for (const [sec, list] of bySection) {
  if (!inScope(sec)) continue;
  lines.push(`| ${sec} ${sections.get(sec)} | ${list.length} | ${implemented(list)} (${pct(implemented(list), list.length)}) | ${count(list, "tested")} |`);
}
const out = rules.filter((r) => !inScope(r.section));
lines.push(`| 800-999 (out of scope) | ${out.length} | ${implemented(out)} | ${count(out, "tested")} |`);
lines.push("");
lines.push("## Checklist");
const mark = { tested: "✅", cited: "🟡", "test only": "🧪", "not yet": "⬜" };
for (const [sec, list] of bySection) {
  if (!inScope(sec)) continue;
  lines.push("");
  lines.push(`### ${sec} ${sections.get(sec)} (${implemented(list)}/${list.length})`);
  lines.push("");
  for (const r of list) {
    const text = r.text.length > 110 ? `${r.text.slice(0, 107)}...` : r.text;
    lines.push(`- ${mark[status(r.id)]} ${r.id} ${text}`);
  }
}
const report = lines.join("\n") + "\n";

const i = process.argv.indexOf("--out");
if (i > 0) writeFileSync(`${root}${process.argv[i + 1]}`, report);
console.log(`rules 100-799: ${implemented(inScopeRules)} of ${inScopeRules.length} implemented (${pct(implemented(inScopeRules), inScopeRules.length)}), ${count(inScopeRules, "tested")} tested`);
const unknown = [...engine.keys()].filter((id) => !rules.some((r) => r.id === id));
if (unknown.length) console.log(`cited but not in the CR (wrong citations to fix): ${unknown.sort().join(", ")}`);
