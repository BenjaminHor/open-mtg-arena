// Generates the JavaScript module that puts the Odin engine behind the exact interface the client imports today
// (D-187): every function declared in client/src/wasm/<name>.d.ts, same names and arguments, JSON values in and out.
// Each call becomes one request {"fn": name, "args": [...]} to the Odin module's `call` export; the reply is
// {"ok": value} or {"err": message} (thrown as an Error, as the wasm-bindgen glue throws engine errors).
//
// Usage: node odin/engine-wasm/gen-glue.mjs <d.ts> <wasm file name> <out.js>
// e.g.   node odin/engine-wasm/gen-glue.mjs client/src/wasm/engine_wasm.d.ts engine_odin.wasm client/src/wasm-odin/engine_wasm.js
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname } from "node:path";

const [dts, wasmName, out] = process.argv.slice(2);
if (!dts || !wasmName || !out) {
  console.error("usage: gen-glue.mjs <d.ts> <wasm file name> <out.js>");
  process.exit(2);
}

// The wasm-bindgen plumbing the client never calls through the engine (it calls them as module setup) and the
// byte-level state codec, which the glue implements itself (below).
const SKIP = new Set(["initSync"]);
const IN_GLUE = new Set(["state_codec_decode", "state_codec_encode", "state_codec_for_viewer", "state_codec_from_json", "take_last_panic_message"]);

const fns = [];
for (const line of readFileSync(dts, "utf8").split("\n")) {
  const m = line.match(/^export function (\w+)\((.*)\): (.+);$/);
  if (!m || SKIP.has(m[1])) continue;
  const params = m[2].trim() === "" ? [] : splitTop(m[2]).map((p) => p.trim().split(/\??:/)[0].trim());
  fns.push({ name: m[1], params, returns: m[3].trim() });
}

// Splits a parameter list at top-level commas (types like `{ a: X, b: Y }` keep theirs).
function splitTop(s) {
  const parts = [];
  let depth = 0, cur = "";
  for (const ch of s) {
    if ("{([<".includes(ch)) depth++;
    if ("})]>".includes(ch)) depth--;
    if (ch === "," && depth === 0) { parts.push(cur); cur = ""; } else cur += ch;
  }
  if (cur.trim()) parts.push(cur);
  return parts;
}

const generated = fns
  .filter((f) => !IN_GLUE.has(f.name))
  .map((f) => {
    const args = f.params.join(", ");
    const body = f.returns === "void" ? `  call(${JSON.stringify(f.name)}, [${args}]);` : `  return call(${JSON.stringify(f.name)}, [${args}]);`;
    return `export function ${f.name}(${args}) {\n${body}\n}`;
  })
  .join("\n\n");

const code = `// GENERATED by odin/engine-wasm/gen-glue.mjs from ${dts}: the Odin engine behind the client's existing engine
// interface (D-187). Do not edit; regenerate.
let wasm = null;
let lastPanic = undefined;
const enc = new TextEncoder();
const dec = new TextDecoder();

// Odin's js_wasm32 runtime imports: console output and random bytes (hash-map seeding).
function imports() {
  return {
    odin_env: {
      write: (fd, ptr, len) => {
        const text = dec.decode(new Uint8Array(wasm.memory.buffer, ptr, len));
        (fd === 2 ? console.error : console.log)(text);
      },
      rand_bytes: (ptr, len) => crypto.getRandomValues(new Uint8Array(wasm.memory.buffer, ptr, len)),
      time_now: () => BigInt(Date.now()) * 1000000n,
      tick_now: () => performance.now(),
      time_sleep: () => {},
      trap: () => { throw new Error("odin trap"); },
      alert: () => {},
      abort: () => { throw new Error("odin abort"); },
      evaluate: () => {},
      sqrt: Math.sqrt, sin: Math.sin, cos: Math.cos, pow: Math.pow, fmuladd: (a, b, c) => a * b + c,
      ln: Math.log, exp: Math.exp, ldexp: (x, e) => x * Math.pow(2, e),
    },
  };
}

// JSON with bigints written as strings (the Odin side reads a u64 from either).
const replacer = (_k, v) => (typeof v === "bigint" ? v.toString() : v);

function call(fn, args) {
  if (!wasm) throw new Error("engine not initialized");
  const bytes = enc.encode(JSON.stringify({ fn, args }, replacer));
  const ptr = wasm.alloc_bytes(bytes.length);
  new Uint8Array(wasm.memory.buffer, ptr, bytes.length).set(bytes);
  const n = wasm.call(ptr, bytes.length);
  const text = dec.decode(new Uint8Array(wasm.memory.buffer, wasm.result_ptr(), n));
  const reply = JSON.parse(text);
  if (reply.err !== undefined) {
    lastPanic = reply.err;
    // Named in the console so a run shows what the Odin engine doesn't serve yet.
    console.warn(\`[odin engine] \${fn}: \${reply.err}\`);
    throw new Error(reply.err);
  }
  return reply.ok === null ? undefined : reply.ok;
}

// The state codec: an immutable JSON holder, as the Rust engine's handle is.
export class StateCodecHandle {
  constructor(json, revision) { this._json = json; this._revision = revision; }
  free() {}
  [Symbol.dispose]() {}
  clone_handle() { return new StateCodecHandle(this._json, this._revision); }
  hash() { return fnv1aHex(this._json); }
  json() { return this._json; }
  json_bytes() { return enc.encode(this._json); }
  revision() { return this._revision; }
  with_revision(revision) { return new StateCodecHandle(this._json, revision); }
}
function fnv1aHex(s) {
  let h = 0xcbf29ce484222325n;
  for (const b of enc.encode(s)) { h ^= BigInt(b); h = (h * 0x100000001b3n) & 0xffffffffffffffffn; }
  return h.toString(16).padStart(64, "0");
}
export function state_codec_decode(bytes, _baseline) { return new StateCodecHandle(dec.decode(bytes)); }
export function state_codec_encode(state, _baseline) { return enc.encode(state.json()); }
export function state_codec_for_viewer(viewer) { return new StateCodecHandle(JSON.stringify(call("get_filtered_game_state_json", [viewer ?? null]))); }
export function state_codec_from_json(bytes) { return new StateCodecHandle(dec.decode(bytes)); }
export function take_last_panic_message() { const m = lastPanic; lastPanic = undefined; return m; }

${generated}

async function load(input) {
  if (input && typeof input === "object" && "module_or_path" in input) input = await input.module_or_path;
  if (input === undefined) input = new URL(${JSON.stringify(wasmName)}, import.meta.url);
  if (input instanceof WebAssembly.Module) return WebAssembly.instantiate(input, imports());
  if (typeof input === "string" || input instanceof URL || input instanceof Request) input = fetch(input);
  const resp = await input;
  const bytes = resp instanceof Response ? await resp.arrayBuffer() : resp;
  return (await WebAssembly.instantiate(bytes, imports())).instance;
}

export function initSync(module) {
  if (module && typeof module === "object" && "module" in module) module = module.module;
  const m = module instanceof WebAssembly.Module ? module : new WebAssembly.Module(module);
  wasm = new WebAssembly.Instance(m, imports()).exports;
  return wasm;
}

export default async function init(input) {
  if (wasm) return wasm;
  const inst = await load(input);
  wasm = (inst.instance ?? inst).exports;
  return wasm;
}
`;

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, code);
console.log(`${out}: ${fns.length - [...IN_GLUE].filter((n) => fns.some((f) => f.name === n)).length} engine calls, ${IN_GLUE.size} in the glue`);
